import { StatCard, usd, num } from './CostUi';

// Day totals: exact dollar cost on the Anthropic key, plus the platform-credit
// calls that have no per-token price.
export default function CostSummaryCards({ report }) {
  const perCall = report.totalAICalls ? report.totalCostUsd / report.totalAICalls : 0;
  return (
    <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(165px, 1fr))', gap: '12px' }}>
      <StatCard label="Exact AI Cost" value={usd(report.totalCostUsd)} sub="Anthropic key, from real tokens" accent />
      <StatCard label="Total AI Calls" value={num(report.totalAICalls)} sub={`${num(report.anthropicCalls)} exact · ${num(report.platformCalls)} platform`} />
      <StatCard label="Avg per AI Call" value={usd(perCall)} sub="Across every AI call" />
      <StatCard label="Input Tokens" value={num(report.inputTokens)} sub={`${num(report.cacheReadTokens + report.cacheWriteTokens)} cached`} />
      <StatCard label="Output Tokens" value={num(report.outputTokens)} sub="Generated by the AI" />
      <StatCard label="Calls With AI" value={num(report.callCount)} sub={`${num(report.estimatedPlatformCredits)} est. platform credits`} />
    </div>
  );
}