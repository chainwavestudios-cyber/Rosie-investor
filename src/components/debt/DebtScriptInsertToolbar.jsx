import React from 'react';
import { CUE_CATEGORIES } from '@/components/debt/ScriptTeleprompter';
import { DEBT_INLINE_FIELDS } from '@/components/debt/DebtInlineField';
import { DEBT_CONTACT_TABS } from '@/lib/debtContactFields';

const ACTIONS = [
  ['💰 Debt Confirm', '@@DEBT_CONFIRM@@'],
  ['✅ Completed Steps', '@@COMPLETED_STEPS@@'],
  ['🤖 AI Input', '@@AI_INPUT@@'],
  ['📧 Send Credentials & Welcome Email', '@@SEND_EMAIL@@'],
  ['✉ Send Text via Android', '@@SEND_TEXT@@'],
];

export default function DebtScriptInsertToolbar({ variables, onInsert, onCaptureSelection, accent }) {
  const buttonStyle = { color: accent, borderColor: `${accent}55`, background: `${accent}12` };
  const buttonClass = 'rounded border px-2 py-1.5 text-xs font-semibold';
  const insert = (text) => onInsert(`<br>${text}<br>`);
  return (
    <div className="mb-2 shrink-0 space-y-2" onMouseDownCapture={onCaptureSelection}>
      <div className="flex flex-wrap items-center gap-1.5" role="group" aria-label="Insert Variable">
        <span className="text-xs text-assistant-muted">Insert Variable:</span>
        {variables.map(({ token, desc }) => <button type="button" key={token} title={desc} onMouseDown={e => e.preventDefault()} onClick={() => onInsert(token)} className={buttonClass} style={buttonStyle}>{token}</button>)}
      </div>
      <div className="flex flex-wrap items-center gap-1.5" role="group" aria-label="Insert Cue">
        <span className="text-xs text-assistant-muted">Insert Cue:</span>
        {Object.entries(CUE_CATEGORIES).map(([key, cue]) => <button type="button" key={key} onMouseDown={e => e.preventDefault()} onClick={() => insert(`@@CUE:${key}:New ${cue.label.toLowerCase()}@@`)} className={buttonClass} style={buttonStyle}>{cue.icon} {cue.label}</button>)}
        <select aria-label="AI Field Tag" defaultValue="" onChange={e => { if (e.target.value) onInsert(` [[AI:${e.target.value}]] `); e.target.value = ''; }} className={`${buttonClass} max-w-full`} style={buttonStyle}>
          <option value="" disabled>🤖 AI Field Tag…</option>
          {DEBT_CONTACT_TABS.map(tab => <optgroup key={tab.key} label={tab.label} className="bg-assistant-surface text-assistant-ink">
            <option value={tab.tag}>Whole tab — {tab.label}</option>
            {tab.fields.map(field => <option key={field.field} value={field.field}>{field.label}</option>)}
          </optgroup>)}
        </select>
        {ACTIONS.map(([label, tag]) => <button type="button" key={tag} onMouseDown={e => e.preventDefault()} onClick={() => insert(tag)} className={buttonClass} style={buttonStyle}>{label}</button>)}
      </div>
      <div className="flex flex-wrap items-center gap-1.5" role="group" aria-label="Insert Contact Field">
        <span className="text-xs text-assistant-muted">Contact Field:</span>
        {DEBT_INLINE_FIELDS.map(f => (
          <button type="button" key={f.key} title={`Edit and save ${f.label.toLowerCase()} on the contact card from inside the script`} onMouseDown={e => e.preventDefault()} onClick={() => insert(`@@FIELD:${f.key}@@`)} className={buttonClass} style={buttonStyle}>{f.label}</button>
        ))}
      </div>
      <p className="text-xs text-assistant-muted">AI tags guide collection into customer fields and stay hidden while reading. Activity, Q&amp;A, transcripts, research and completion history are generated by their existing tools, not invented from tags.</p>
    </div>
  );
}